// Builds a throwaway, test-only copy of browser-extension/ under
// test-results/extension-under-test (gitignored) for the real-browser
// extension runtime test (tests-extension/runtime.spec.ts).
//
// It never touches the shipped extension files or manifests. Three changes
// are made only in the copy:
//
//  1. manifest.json's host_permissions and the Meet content_script's
//     `matches` gain one extra pattern, "http://127.0.0.1:*/meet-fixture/*"
//     (Chrome/Edge match patterns support a literal or "*" port since Chrome
//     50), so the unmodified content-meet.js/content-logic.js/
//     content-runtime.js run against a locally served fixture page instead
//     of the real meet.google.com. The shipped manifest.json/
//     manifest.firefox.json never gain this pattern.
//  2. background.js is renamed to background.original.js, and a new
//     background.js is written that imports a test-only shim before it --
//     the shim stubs chrome.runtime.connectNative so the test never spawns
//     (or requires) the real native-messaging host, and captures every
//     outgoing message into chrome.storage.session for the test to read.
//     background.original.js's behaviour, and every other file, is an exact
//     byte-for-byte copy of the source.
//  3. content-runtime.js's poll/heartbeat intervals are shortened (2000ms ->
//     400ms, 15000ms -> 2500ms) purely so the test doesn't have to wait out
//     the real 15s heartbeat cadence. This only affects the test copy.
//
// Run directly (`node scripts/build-extension-test.mjs [outDir]`) or import
// `buildExtensionForTest(outDir)` from a test.
import { cpSync, mkdirSync, readFileSync, writeFileSync, rmSync, renameSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC_DIR = path.join(here, "..", "browser-extension");
export const DEFAULT_OUT_DIR = path.join(here, "..", "test-results", "extension-under-test");

// Restricted to 127.0.0.1 on the one port the test's static fixture server
// is actually listening on, and to the /meet-fixture/ path it serves from --
// never a bare "/*", a wildcard host, or a wildcard port (Chrome's
// web_accessible_resources match-pattern validation rejects a wildcard port
// outright -- "Invalid value for 'web_accessible_resources[0]'. Invalid
// match pattern.", which fails the whole extension load, discovered while
// writing this build step), so this stays nowhere close to <all_urls>.
export function testHostPattern(port) {
  return `http://127.0.0.1:${port}/meet-fixture/*`;
}

// web_accessible_resources' `matches` uses a stricter match-pattern
// validator than host_permissions/content_scripts: Chrome rejects any
// pattern whose path is more specific than a bare "/*" (confirmed while
// writing this build step -- "https://app.zoom.us/wc/*" is valid in
// content_scripts.matches/host_permissions but "Invalid match pattern" in
// web_accessible_resources.matches). So this is scoped to the origin, not
// the fixture path.
export function testOriginPattern(port) {
  return `http://127.0.0.1:${port}/*`;
}

const TEST_SHIM_SOURCE = `// Test-only shim, generated by scripts/build-extension-test.mjs. Never part
// of the shipped extension. Stubs chrome.runtime.connectNative so the
// extension runtime test can run without a real native-messaging host
// installed, and records every message the extension would have sent it
// into chrome.storage.session, where the test reads it back via the
// extension's service worker.
function makeFakeNativePort() {
  const listeners = [];
  return {
    onDisconnect: {
      addListener(fn) {
        listeners.push(fn);
      },
    },
    postMessage(message) {
      chrome.storage.session.get({ capturedMessages: [] }).then(({ capturedMessages }) => {
        capturedMessages.push({ ...message, _receivedAt: Date.now() });
        chrome.storage.session.set({ capturedMessages });
      });
    },
  };
}

chrome.runtime.connectNative = function connectNative() {
  return makeFakeNativePort();
};
`;

function patchManifest(manifestPath, port) {
  const pattern = testHostPattern(port);
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  manifest.host_permissions = [...(manifest.host_permissions || []), pattern];
  const meetContentScript = (manifest.content_scripts || []).find((entry) =>
    (entry.js || []).includes("content-meet.js")
  );
  if (!meetContentScript) {
    throw new Error("build-extension-test: could not find the Meet content_scripts entry to patch");
  }
  meetContentScript.matches = [...meetContentScript.matches, pattern];
  const runtimeResourceEntry = (manifest.web_accessible_resources || []).find((entry) =>
    (entry.resources || []).includes("content-runtime.js")
  );
  if (!runtimeResourceEntry) {
    throw new Error(
      "build-extension-test: could not find the web_accessible_resources entry to patch"
    );
  }
  runtimeResourceEntry.matches = [...runtimeResourceEntry.matches, testOriginPattern(port)];
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
}

function patchBackground(outDir) {
  const backgroundPath = path.join(outDir, "background.js");
  const originalPath = path.join(outDir, "background.original.js");
  renameSync(backgroundPath, originalPath);
  writeFileSync(
    path.join(outDir, "test-shim.js"),
    TEST_SHIM_SOURCE
  );
  writeFileSync(
    backgroundPath,
    `// Generated by scripts/build-extension-test.mjs -- imports the test shim\n` +
      `// before the real (unmodified) background script.\n` +
      `import "./test-shim.js";\n` +
      `import "./background.original.js";\n`
  );
}

function patchRuntimeTiming(outDir) {
  const runtimePath = path.join(outDir, "content-runtime.js");
  let source = readFileSync(runtimePath, "utf8");
  const replacements = [
    [/const HEARTBEAT_MS = 15000;/, "const HEARTBEAT_MS = 2500;"],
    [/const POLL_MS = 2000;/, "const POLL_MS = 400;"],
  ];
  for (const [pattern, replacement] of replacements) {
    if (!pattern.test(source)) {
      throw new Error(`build-extension-test: expected to find ${pattern} in content-runtime.js`);
    }
    source = source.replace(pattern, replacement);
  }
  writeFileSync(runtimePath, source);
}

/**
 * @param {string} outDir
 * @param {{ fixtureServerPort: number }} options - the port the test's local
 *   fixture HTTP server is (already) listening on; baked into the test
 *   manifest's match patterns as a concrete port (see testHostPattern above).
 */
export function buildExtensionForTest(outDir = DEFAULT_OUT_DIR, { fixtureServerPort } = {}) {
  if (!fixtureServerPort) {
    throw new Error("build-extension-test: fixtureServerPort is required");
  }
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  cpSync(SRC_DIR, outDir, {
    recursive: true,
    filter: (src) => {
      const rel = path.relative(SRC_DIR, src);
      if (rel === "test" || rel.startsWith(`test${path.sep}`)) return false;
      if (rel === "key" || rel.startsWith(`key${path.sep}`)) return false;
      return true;
    },
  });
  patchManifest(path.join(outDir, "manifest.json"), fixtureServerPort);
  patchBackground(outDir);
  patchRuntimeTiming(outDir);
  return outDir;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const port = Number(process.argv[3] || process.argv[2]);
  if (!port) {
    console.error("Usage: node scripts/build-extension-test.mjs [outDir] <fixtureServerPort>");
    process.exit(1);
  }
  const outDir = process.argv[3] ? process.argv[2] : DEFAULT_OUT_DIR;
  const built = buildExtensionForTest(outDir, { fixtureServerPort: port });
  console.log(`Test extension built at ${built}`);
}
